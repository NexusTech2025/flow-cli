/**
 * lucid-exporter.js
 * Exporters for Lucidchart Process CSV, Light-Themed Mermaid, and Portable JSON.
 */

import { THEME_PALETTE } from './graph-model.js';

export class LucidExporter {
  /**
   * Escape fields for CSV format
   */
  static escapeCsvField(val) {
    if (val === null || val === undefined) return '""';
    const str = String(val);
    if (str.includes(',') || str.includes('"') || str.includes('\n') || str.includes('\r')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return `"${str}"`;
  }

  /**
   * Export DiagramGraph to official Lucidchart Process Diagram CSV
   */
  static toLucidCsv(graph) {
    const nodes = graph.getNodes();
    const edges = graph.edges;

    // Map internal node IDs to consistent numerical/clean IDs for Lucidchart
    const idMap = new Map();
    nodes.forEach((n, idx) => {
      idMap.set(n.id, idx + 1);
    });

    const shapeRows = [
      'Id,Name,Shape Library,Page ID,Contained By,Line Style,Shape Type,Text Area 1,Description,Status',
    ];

    for (const node of nodes) {
      const lucidId = idMap.get(node.id);
      const name = node.label;
      const shapeLib = 'standard';
      const pageId = '1';
      const containedBy = '';
      const lineStyle = 'solid';
      const shapeType = node.shapeType || 'Process';

      // Build Text Area 1: Label + bullet details
      let textAreaContent = node.label;
      if (node.details && node.details.length > 0) {
        textAreaContent += '\n' + node.details.map((d) => `• ${d}`).join('\n');
      }

      const description = node.description || '';
      const status = THEME_PALETTE[node.status]?.badge || 'NORMAL';

      shapeRows.push(
        [
          lucidId,
          this.escapeCsvField(name),
          shapeLib,
          pageId,
          containedBy,
          lineStyle,
          shapeType,
          this.escapeCsvField(textAreaContent),
          this.escapeCsvField(description),
          status,
        ].join(',')
      );
    }

    const connectionRows = [
      'Line Style,Source,Target,Text Area 1,Arrowhead',
    ];

    for (const edge of edges) {
      const sourceId = idMap.get(edge.source);
      const targetId = idMap.get(edge.target);
      if (!sourceId || !targetId) continue;

      const lineStyle = edge.lineStyle || 'solid';
      const label = edge.label ? this.escapeCsvField(edge.label) : '';
      const arrowhead = edge.arrowhead || 'Arrow';

      connectionRows.push(
        [lineStyle, sourceId, targetId, label, arrowhead].join(',')
      );
    }

    // Official Lucidchart format: Shapes section, empty line, Connections section
    return `${shapeRows.join('\n')}\n\n${connectionRows.join('\n')}\n`;
  }

  /**
   * Escape HTML entities for Mermaid labels
   */
  static escapeMermaidText(str) {
    if (!str) return '';
    return str
      .replace(/&/g, '&amp;')
      .replace(/"/g, '&quot;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
  }

  /**
   * Export DiagramGraph to Lucidchart Light-Theme Mermaid
   */
  static toMermaid(graph) {
    const lines = [];
    lines.push(`flowchart ${graph.direction || 'TD'}`);
    lines.push('    %% --- Generated by LucidFlow Architect ---');

    const nodes = graph.getNodes();
    const nodeIdMap = new Map();

    // Node declarations (with Subgraphs)
    lines.push('    %% Node Definitions');
    const containerGroups = new Map();
    const topNodes = [];

    nodes.forEach((n, idx) => {
      const mId = `N${idx + 1}`;
      nodeIdMap.set(n.id, mId);

      const cId = n.customData?.container;
      if (cId) {
        if (!containerGroups.has(cId)) {
          containerGroups.set(cId, {
            title: n.customData?.containerTitle || cId,
            nodes: [],
          });
        }
        containerGroups.get(cId).nodes.push({ node: n, mId });
      } else {
        topNodes.push({ node: n, mId });
      }
    });

    const formatNodeLine = (n, mId) => {
      const escapedLabel = this.escapeMermaidText(n.label);
      let content = `<b>${escapedLabel}</b>`;

      if (n.details && n.details.length > 0) {
        const detailSnippet = n.details
          .slice(0, 3)
          .map((d) => `• ${this.escapeMermaidText(d)}`)
          .join('<br/>');
        content += `<br/><small>${detailSnippet}</small>`;
      } else if (n.description) {
        content += `<br/><small>${this.escapeMermaidText(n.description)}</small>`;
      }

      let shapeSyntax = `["${content}"]`;
      if (n.shapeType === 'Terminator') {
        shapeSyntax = `(["${content}"])`;
      } else if (n.shapeType === 'Decision') {
        shapeSyntax = `{"${content}"}`;
      }

      const statusClass = THEME_PALETTE[n.status] ? n.status : 'normal';
      return `    ${mId}${shapeSyntax}:::${statusClass}`;
    };

    topNodes.forEach(({ node, mId }) => {
      lines.push(formatNodeLine(node, mId));
    });

    containerGroups.forEach((group, cId) => {
      lines.push('');
      lines.push(`    subgraph ${cId} ["<b>${this.escapeMermaidText(group.title)}</b>"]`);
      lines.push('        direction TB');
      group.nodes.forEach(({ node, mId }) => {
        lines.push('    ' + formatNodeLine(node, mId));
      });
      lines.push('    end');
    });

    // Edges
    lines.push('');
    lines.push('    %% Edge Connections');
    for (const edge of graph.edges) {
      const sId = nodeIdMap.get(edge.source);
      const tId = nodeIdMap.get(edge.target);
      if (!sId || !tId) continue;

      if (edge.label) {
        const escapedEdgeLabel = this.escapeMermaidText(edge.label);
        lines.push(`    ${sId} -- "${escapedEdgeLabel}" --> ${tId}`);
      } else {
        lines.push(`    ${sId} --> ${tId}`);
      }
    }

    // Light Theme Style Classes
    lines.push('');
    lines.push('    %% Lucidchart Light Theme Palette Styling');
    for (const [key, t] of Object.entries(THEME_PALETTE)) {
      lines.push(
        `    classDef ${key} fill:${t.fill},stroke:${t.stroke},stroke-width:2px,color:${t.text};`
      );
    }

    return lines.join('\n') + '\n';
  }

  /**
   * Export DiagramGraph to Portable JSON
   */
  static toJson(graph, pretty = true) {
    return pretty
      ? JSON.stringify(graph.toJSON(), null, 2)
      : JSON.stringify(graph.toJSON());
  }
}
